import { Activity } from "../api";

export function getGoogleCalendarUrl(activity: Activity): string {
  const start = new Date(Date.now() + 60 * 60 * 1000); // 1 hour from now
  const end = new Date(
    start.getTime() + (activity.durationMin || 60) * 60 * 1000,
  );

  const formatTime = (d: Date) => d.toISOString().replace(/-|:|\.\d\d\d/g, "");

  const title = encodeURIComponent(`Chicken Tinder: ${activity.title}`);
  const details = encodeURIComponent(
    `${activity.description}\n\nCategory: ${activity.category}\nDuration: ${activity.durationMin} mins\nGenerated by Chicken Tinder (chickentinder.app)`,
  );
  const dates = `${formatTime(start)}/${formatTime(end)}`;

  return `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${title}&details=${details}&dates=${dates}`;
}

export function downloadIcsFile(activity: Activity) {
  const start = new Date(Date.now() + 60 * 60 * 1000);
  const end = new Date(
    start.getTime() + (activity.durationMin || 60) * 60 * 1000,
  );

  const formatIcsTime = (d: Date) =>
    d.toISOString().replace(/-|:|\.\d\d\d/g, "");

  const icsContent = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Chicken Tinder//Activity Scheduler//EN",
    "BEGIN:VEVENT",
    `UID:${activity.id || Date.now()}@chickentinder.app`,
    `DTSTAMP:${formatIcsTime(new Date())}`,
    `DTSTART:${formatIcsTime(start)}`,
    `DTEND:${formatIcsTime(end)}`,
    `SUMMARY:Chicken Tinder: ${activity.title.replace(/,/g, "\\,")}`,
    `DESCRIPTION:${activity.description.replace(/,/g, "\\,")}`,
    "STATUS:CONFIRMED",
    "END:VEVENT",
    "END:VCALENDAR",
  ].join("\r\n");

  const blob = new Blob([icsContent], { type: "text/calendar;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${activity.title
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "-")
    .slice(0, 30)}.ics`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function getMapsSearchUrl(activity: Activity): string {
  const query = `${activity.title} near me`;
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

export function getIngredientsChecklist(activity: Activity): string[] {
  const text = `${activity.title} ${activity.description}`.toLowerCase();

  if (activity.category === "culinary") {
    if (text.includes("pizza"))
      return [
        "Pizza dough / flour",
        "San Marzano tomatoes",
        "Fresh mozzarella",
        "Fresh basil",
        "Olive oil",
      ];
    if (text.includes("sushi"))
      return [
        "Sushi rice",
        "Nori seaweed sheets",
        "Fresh salmon / tuna",
        "Cucumber & avocado",
        "Soy sauce & wasabi",
      ];
    if (text.includes("ramen"))
      return [
        "Ramen noodles",
        "Savory broth / bones",
        "Green scallions",
        "Soft-boiled egg",
        "Garlic & chili oil",
      ];
    if (text.includes("tacos"))
      return [
        "Corn tortillas",
        "Fresh cilantro & onion",
        "Limes",
        "Salsa verde / roja",
        "Protein of choice",
      ];
    if (text.includes("pasta"))
      return [
        "00 Flour & eggs",
        "Parmigiano / Pecorino",
        "Garlic & olive oil",
        "Fresh herbs",
      ];
    return [
      "Fresh herbs",
      "Quality olive oil",
      "Seasonings / spices",
      "Recipe ingredients",
      "Cookware & skillet",
    ];
  }

  if (activity.category === "outdoor") {
    return [
      "Comfortable walking shoes",
      "Water bottle",
      "Weather-appropriate layers",
      "Fully charged phone / camera",
      "Small daypack",
    ];
  }

  if (activity.category === "fitness") {
    return [
      "Workout attire & runners",
      "Electrolyte water",
      "Hand towel",
      "Gym pass / open court",
      "Headphones & playlist",
    ];
  }

  if (activity.category === "creative") {
    return [
      "Sketchbook / canvas",
      "Pencils / brushes / paints",
      "Good natural lighting",
      "Inspirational reference",
      "Quiet workspace",
    ];
  }

  return [
    "Open mind & curiosity",
    "30-60 minutes free time",
    "Good company or headphones",
  ];
}
